/** Карточка лиги персонала в разделе обучения */
export interface TutorialTierCard {
  /** Ключ картинки из tierImages */
  imageKey: string
  /** Название лиги */
  name: string
  /** Короткое описание: прирост скорости и порог открытия */
  description: string
}

/** Раздел обучения: заголовок аккордеона, иконка и его содержимое */
