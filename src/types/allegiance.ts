/**
 * Лояльность коллектива к руководителю.
 * Считается окнами: ALLEGIANCE_WINDOW выборов, затем окно закрывается
 * и счётчики обнуляются.
 */
export interface Allegiance {
  /** Сколько выборов учтено в текущем окне (от 0 до ALLEGIANCE_WINDOW) */
  current: number;
  /** Среднее арифметическое разовых значений в текущем окне (от 0 до 100) */
  agression: number;
}

/**
 * Уровень агрессивности: текст для модалки и экономический эффект.
 * Границы образуют непрерывную шкалу 0..100, нижняя включается, верхняя нет.
 */
export interface AllegianceEpisode {
  id: number;
  /** Нижняя граница агрессивности, включительно */
  min: number;
  /** Верхняя граница агрессивности, не включительно */
  max: number;
  title: string;
  /** Варианты текста модалки: показывается один случайный */
  description: string[];
  influence: 'positive' | 'negative';
  /** Доля money, которая меняется при этом уровне */
  rate: number;
}
