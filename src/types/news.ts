/** Источник новости: откуда пришло событие */
export type NewsKind = 'offline' | 'global' | 'locale'

/**
 * Новость о произошедшем событии.
 * Деньги по событию уже начислены или списаны к моменту появления новости,
 * поэтому окно новостей только информирует игрока.
 */
export interface NewsItem {
  /** Уникальный идентификатор новости */
  id: string
  /** Источник события */
  kind: NewsKind
  /** Заголовок новости */
  title: string
  /** Текст новости */
  description: string
  /** Изменение баланса: положительное — доход, отрицательное — убыток */
  amount: number
}
